#!/usr/bin/env python3
"""
Weekly Vault Digest — consolidates the entire vault into a searchable weekly summary.
Enforces: every file must have at least one link to its encapsulating folder context.

Usage: python3 vault-digest.py
Workdir: /home/thomas/Desktop/Memory
Output: AI/WeeklyDigests/YYYY-WXX.md
Schedule: Every Monday at 20:00 (via cron job vault-weekly-digest)
"""
import os, re, yaml, subprocess, json
from collections import Counter
from datetime import datetime

# ── CONFIG ────────────────────────────────────────────────────────────────────
VAULT_PATH = os.path.expanduser("/home/thomas/Desktop/Memory")
DIGEST_DIR = "AI/WeeklyDigests"
WIKILINK_RE = re.compile(r'\[\[([^\]]+)\]\]')

# ── SCAN VAULT ─────────────────────────────────────────────────────────────────
def scan_vault():
    files = []
    for root, dirs, filenames in os.walk(VAULT_PATH):
        if '.obsidian' in root:
            continue
        for fn in filenames:
            if fn.endswith('.md'):
                fpath = os.path.join(root, fn)
                content = open(fpath, errors='ignore').read()
                title = os.path.splitext(fn)[0]
                if content.startswith('---'):
                    try:
                        fm = yaml.safe_load(content.split('---', 2)[1])
                        if fm and isinstance(fm, dict) and 'title' in fm:
                            title = str(fm['title'])
                    except:
                        pass
                rel = fpath.replace(VAULT_PATH + '/', '')
                parts = rel.split('/')
                folder = parts[0] if parts else ''
                sub = parts[1:-1] if len(parts) > 1 else []
                links_raw = WIKILINK_RE.findall(content)
                files.append({
                    'path': fpath, 'title': title, 'folder': folder,
                    'subfolders': sub, 'relpath': rel,
                    'links_raw': links_raw, 'content': content
                })
    return files

# ── RESOLVE LINKS ──────────────────────────────────────────────────────────────
def build_resolved_links(files):
    title_map = {f['title'].lower(): f for f in files}
    path_map = {f['relpath']: f for f in files}
    orphan_count = 0
    for f in files:
        f['_valid_links'] = []
        for link_raw in f['links_raw']:
            lt = link_raw.split('|')[0].split('#')[0].strip().lower()
            if lt in title_map:
                target = title_map[lt]
                f['_valid_links'].append((target['title'], target['folder'], target['relpath']))
            else:
                for rp, fi in path_map.items():
                    if rp.lower() == f'{lt}.md':
                        f['_valid_links'].append((fi['title'], fi['folder'], fi['relpath']))
                        break
        has_same = any(tf == f['folder'] for _, tf, _ in f['_valid_links'])
        if not has_same:
            orphan_count += 1
    return title_map, path_map, orphan_count

# ── FOLDER ANCHORING ───────────────────────────────────────────────────────────
def ensure_folder_anchor(f, all_files, title_map, path_map):
    folder = f['folder']
    relpath = f['relpath']
    sub = f['subfolders']

    if folder == 'Projects':
        parts = relpath.split('/')
        if len(parts) >= 2:
            proj = parts[1]
            for c in [f'Projects/{proj}/overview.md', f'Projects/{proj}/README.md']:
                if c in path_map:
                    return path_map[c]['title'], c
        return None, None

    elif folder == 'Research':
        if len(sub) >= 2:
            # Find cluster — skip infrastructure subfolders (pages, 99-Meta, _Lot*)
            cluster = None
            for s in sub:
                if s not in ('pages', '99-Meta') and not s.startswith('_'):
                    cluster = s
                    break
            if not cluster:
                cluster = sub[-1] if sub else None
            if not cluster:
                return 'Research', None
            cluster_root = f'Research/{cluster}'
            candidates = [f'{cluster_root}/_MOC.md', f'{cluster_root}/index.md',
                          f'{cluster_root}/README.md', f'{cluster_root}/Schema.md']
            for c in candidates:
                if c in path_map:
                    return path_map[c]['title'], c
            # Auto-create cluster _MOC.md if missing
            moc_path = os.path.join(VAULT_PATH, f'{cluster_root}/_MOC.md')
            if not os.path.exists(moc_path):
                try:
                    os.makedirs(os.path.dirname(moc_path), exist_ok=True)
                    cluster_title = cluster.replace('-', ' ').replace('_', ' ')
                    with open(moc_path, 'w') as fh:
                        fh.write(f"# {cluster_title}\n\n*Cluster overview — auto-generated by vault-digest*\n\n## Pages\n")
                    path_map[moc_path.replace(VAULT_PATH+'/', '')] = {
                        'title': cluster_title, 'folder': 'Research', 'relpath': moc_path.replace(VAULT_PATH+'/', ''), 'content': ''
                    }
                    return cluster_title, moc_path.replace(VAULT_PATH+'/', '')
                except:
                    pass
            return cluster.replace('-', ' ').replace('_', ' '), None
        return 'Research', None

    elif folder == 'People':
        name = f['title']
        for af in all_files:
            if af['folder'] == 'Projects' and af['relpath'].endswith('overview.md'):
                if name.lower() in af.get('content', '').lower():
                    return af['title'], af['relpath']
        if 'index' in title_map:
            return title_map['index']['title'], 'Projects/index.md'
        return None, None

    elif folder == 'Conversations':
        parts = relpath.split('/')
        if len(parts) >= 3:
            year, month = parts[1], parts[2]
            month_idx_rel = f'Conversations/{year}/{month}/index.md'
            month_idx_path = os.path.join(VAULT_PATH, month_idx_rel)
            month_title = f"{month} Conversations"
            if not os.path.exists(month_idx_path):
                try:
                    os.makedirs(os.path.dirname(month_idx_path), exist_ok=True)
                    month_dir = os.path.dirname(month_idx_path)
                    day_files = sorted([fn.replace('.md', '') for fn in os.listdir(month_dir)
                                        if fn.endswith('.md') and fn not in ('index.md',)])
                    with open(month_idx_path, 'w') as fh:
                        fh.write(f"# {month_title}\n\n*Month index — auto-generated*\n\n")
                        for df in day_files:
                            fh.write(f"- [[{df}]]\n")
                    path_map[month_idx_rel] = {'title': month_title, 'folder': 'Conversations', 'relpath': month_idx_rel, 'content': ''}
                    return month_title, month_idx_rel
                except:
                    pass
            if month_idx_rel in path_map:
                af = path_map[month_idx_rel]
                return af['title'], month_idx_rel
        return 'Conversations', None

    elif folder == 'AI':
        if 'Skills' in sub:
            if 'index' in title_map:
                return title_map['index']['title'], 'AI/Skills/index.md'
            return 'AI/Skills', None
        return None, None

    elif folder == 'Active Context':
        recent = sorted([af for af in all_files if af['folder'] == 'Projects' and af['relpath'].endswith('overview.md')],
                        key=lambda x: os.path.getmtime(x.get('path', '')), reverse=True)
        if recent:
            return recent[0]['title'], recent[0]['relpath']
        return None, None

    return None, None

# ── GENERATE DIGEST ───────────────────────────────────────────────────────────
def generate_digest(files, anchors_applied):
    year, week = datetime.now().isocalendar()[:2]
    digest_path = os.path.join(VAULT_PATH, DIGEST_DIR, f"{year}-W{week:02d}.md")
    os.makedirs(os.path.dirname(digest_path), exist_ok=True)

    folder_counts = Counter(f['folder'] for f in files)
    total_links = sum(len(f['_valid_links']) for f in files)

    lines = [f"# Vault Digest {year}-W{week:02d}\n",
             f"\n**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')} — "
             f"{len(files)} files | {total_links} wikilinks | {len(anchors_applied)} anchors applied\n"]

    # ── Folder overview ──
    lines.append("\n## Vault Overview\n")
    lines.append("| Folder | Files |")
    lines.append("|--------|-------|")
    for fol, cnt in sorted(folder_counts.items(), key=lambda x: -x[1]):
        lines.append(f"| {fol} | {cnt} |")

    # ── Cross-folder bridges ──
    bridges = [(f['title'], t['title'], f['folder'], t['folder'])
               for f in files for _, t, t_f, _ in f['_valid_links']
               if t_f != f['folder']]
    bridge_count = len(set((s, t) for s, t, _, _ in bridges))
    lines.append(f"\n## Cross-Folder Bridges ({bridge_count} unique)\n")
    topics_seen = set()
    for src, tgt, src_f, tgt_f in sorted(bridges, key=lambda x: x[2]):
        key = (src_f, tgt_f)
        if key not in topics_seen:
            lines.append(f"- **{tgt_f}** ← {src_f}: [[{src}]] → [[{tgt}]]")
            topics_seen.add(key)

    # ── Topic clusters ──
    word_counts = Counter()
    for f in files:
        words = re.findall(r'#\w+', f['content'])
        word_counts.update(w for w in words if len(w) > 3)
    lines.append("\n## Active Topics\n")
    for topic, cnt in word_counts.most_common(20):
        lines.append(f"- {topic} ({cnt})")

    # ── Searchable index ──
    lines.append("\n## Full Vault Index\n")
    for folder in sorted(set(f['folder'] for f in files)):
        folder_files = sorted([f for f in files if f['folder'] == folder], key=lambda x: x['title'].lower())
        lines.append(f"\n### {folder}/\n")
        for f in folder_files:
            lines.append(f"- [[{f['title']}]]")

    # ── Anchors applied ──
    if anchors_applied:
        grouped = Counter(a[0] for a in anchors_applied)
        lines.append("\n## Folder Anchors Applied\n")
        for anchor_title, count in sorted(grouped.items(), key=lambda x: -x[1]):
            files_anchored = [a[1] for a in anchors_applied if a[0] == anchor_title]
            lines.append(f"- **[[{anchor_title}]]** ← {count} files")
            for fa in files_anchored[:5]:
                lines.append(f"  - [[{fa}]]")
            if len(files_anchored) > 5:
                lines.append(f"  - ...and {len(files_anchored)-5} more")

    content = '\n'.join(lines)
    with open(digest_path, 'w') as fh:
        fh.write(content)
    return digest_path

# ── MAIN ───────────────────────────────────────────────────────────────────────
def main():
    files = scan_vault()
    title_map, path_map, orphan_count = build_resolved_links(files)

    # Apply folder anchors to orphan files
    anchors_applied = []
    for f in files:
        has_same = any(tf == f['folder'] for _, tf, _ in f['_valid_links'])
        if has_same:
            continue
        anchor_title, anchor_rel = ensure_folder_anchor(f, files, title_map, path_map)
        if not anchor_title:
            continue
        # Verify anchor target exists in title_map
        if anchor_title.lower() not in title_map and not any(a[0].lower() == anchor_title.lower() for a in anchors_applied):
            continue
        target_info = title_map.get(anchor_title.lower())
        if not target_info:
            continue
        anchor_path = target_info['path']
        try:
            with open(anchor_path, 'a') as fh:
                fh.write(f"\n- [[{f['title']}]]\n")
            anchors_applied.append((anchor_title, f['title'], f['relpath'], anchor_rel))
        except:
            pass

    digest_path = generate_digest(files, anchors_applied)

    if anchors_applied:
        try:
            subprocess.run(['git', 'add', '-A'], cwd=VAULT_PATH, capture_output=True)
            result = subprocess.run(['git', 'diff', '--staged', '--stat'], cwd=VAULT_PATH, capture_output=True, text=True)
            changed = result.stdout.strip()
            if changed:
                subprocess.run(['git', 'commit', '-m', f'link: vault-digest anchors + digest {os.path.basename(digest_path)}'], cwd=VAULT_PATH, capture_output=True)
                subp = subprocess.run(['git', 'push', 'origin', 'main'], cwd=VAULT_PATH, capture_output=True, text=True)
                push = 'ok' if subp.returncode == 0 else f'fail: {subp.stderr.strip()}'
            else:
                push = 'no-changes'
        except:
            push = 'git-error'
    else:
        push = 'no-anchors'

    recent_count = sum(1 for f in files if time.time() - os.path.getmtime(f['path']) < 7*86400)
    if recent_count < 3 and not anchors_applied:
        print("NO_ANOMALIES")
    else:
        print(f"Digest: {digest_path}")
        print(f"Files: {len(files)} | Anchors: {len(anchors_applied)} | Recent: {recent_count}")
        print(f"Push: {push}")

if __name__ == '__main__':
    import time
    main()